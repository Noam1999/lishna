// Content model for "לימוד חווייתי" (Experiential Learning).
// Built for scalable rollout: add sedarim → masechtot → dapim → amudim here only.

export interface GlossWord {
  /** The exact token as written inside the text (between [[ ]]) */
  word: string;
  hebrew: string;
  context: string;
}

export interface QuizQuestion {
  question: string;
  options: string[];
  /** index in options */
  correct: number;
  explanation?: string;
}

export interface Amud {
  id: 'a' | 'b';
  label: string; // עמוד א' / עמוד ב'
  /** Gemara text. Target words are wrapped in [[double brackets]] */
  text: string;
  glossary: GlossWord[];
  quiz: QuizQuestion[];
  videoUrl?: string;
}

export interface Daf {
  id: string;
  label: string; // דף ב'
  amudim: Amud[];
}

export interface Masechet {
  id: string;
  label: string;
  dapim: Daf[];
}

export interface Seder {
  id: string;
  label: string;
  masechtot: Masechet[];
}

